"""
spacecraft/thermal.py

A lumped single-node thermal model: the whole spacecraft bus is treated
as one thermal mass exchanging heat with the environment (solar/albedo/
Earth-IR heating when sunlit, radiative cooling when in eclipse) plus
internal dissipation from active subsystems (payload, comms).

This is a simplification of the real multi-node thermal networks used
in spacecraft thermal design, but it captures the behavior that matters
for mission planning: temperature rises during long sunlit/active
periods and falls during eclipse, and the planner needs to keep it
inside operating limits.
"""

from __future__ import annotations
from dataclasses import dataclass
from enum import Enum


class ThermalState(Enum):
    NOMINAL = "NOMINAL"
    WARM = "WARM"
    COLD = "COLD"
    CRITICAL = "CRITICAL"


@dataclass
class ThermalModel:
    temperature_c: float = 20.0

    # Lumped thermal mass * specific heat, effectively "how many J per degree C"
    thermal_capacitance_j_per_c: float = 2000.0

    # Steady-state-ish heating/cooling terms [W]
    solar_heating_w: float = 8.0        # net absorbed heat while sunlit
    eclipse_cooling_w: float = -6.0      # net radiative loss while in eclipse
    passive_radiative_loss_w_per_c: float = 0.15  # extra loss proportional to (T - T_env)
    t_env_c: float = -20.0               # effective deep-space/Earth-IR environment temp

    nominal_range_c: tuple = (-10.0, 40.0)
    warm_limit_c: float = 50.0
    cold_limit_c: float = -20.0
    critical_high_c: float = 60.0
    critical_low_c: float = -30.0

    def step(self, dt_s: float, in_eclipse: bool, internal_dissipation_w: float = 0.0) -> float:
        """
        Advance the thermal state by dt_s seconds.
        internal_dissipation_w: heat generated by active subsystems
        (payload imaging, transmitter, reaction wheels, etc.) this step.
        Returns the new temperature [C].
        """
        env_term = self.eclipse_cooling_w if in_eclipse else self.solar_heating_w
        passive_loss = self.passive_radiative_loss_w_per_c * (self.temperature_c - self.t_env_c)

        net_power_w = env_term + internal_dissipation_w - passive_loss
        d_temp = net_power_w * dt_s / self.thermal_capacitance_j_per_c
        self.temperature_c += d_temp
        return self.temperature_c

    @property
    def state(self) -> ThermalState:
        t = self.temperature_c
        if t >= self.critical_high_c or t <= self.critical_low_c:
            return ThermalState.CRITICAL
        if t >= self.warm_limit_c:
            return ThermalState.WARM
        if t <= self.cold_limit_c:
            return ThermalState.COLD
        return ThermalState.NOMINAL

    def payload_safe(self) -> bool:
        """Whether it's thermally safe to run payload/imaging operations."""
        lo, hi = self.nominal_range_c
        return lo <= self.temperature_c <= hi
